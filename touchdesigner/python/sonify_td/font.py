W, H = 5, 7
_cache = {}


def glyph(ch, scale=1):
    key = (ch, scale)
    g = _cache.get(key)
    if g is None:
        rows = _GLYPHS.get(ch) or _GLYPHS.get(ch.upper()) or _GLYPHS['?']
        m = np.array([[c == '#' for c in r] for r in rows], dtype=bool)
        if scale > 1:
            m = np.repeat(np.repeat(m, scale, axis=0), scale, axis=1)
        _cache[key] = g = m
    return g


def text_width(s, scale=1):
    return max(0, len(s) * (W + 1) * scale - scale)


def draw_text(buf, x, y, s, color, scale=1, align='left'):
    """buf: (H, W, 4) uint8, 위에서 아래로 그리는 좌표. (x, y) = 글자 상자 왼쪽 위. 그린 폭을 돌려준다."""
    width = text_width(s, scale)
    if align == 'right':
        x -= width
    elif align == 'center':
        x -= width // 2
    x, y = int(x), int(y)
    bh, bw = buf.shape[:2]
    col = np.array(color, dtype=np.uint8)
    if col.shape[0] == 3:
        col = np.append(col, 255).astype(np.uint8)
    adv = (W + 1) * scale
    for i, ch in enumerate(s):
        if ch == ' ':
            continue
        g = glyph(ch, scale)
        gx = x + i * adv
        x0, y0 = max(gx, 0), max(y, 0)
        x1, y1 = min(gx + g.shape[1], bw), min(y + g.shape[0], bh)
        if x1 <= x0 or y1 <= y0:
            continue
        m = g[y0 - y:y1 - y, x0 - gx:x1 - gx]
        buf[y0:y1, x0:x1][m] = col
    return width
